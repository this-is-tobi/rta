// missing one's reach. Pinning on the strength of the declarations that *did*
// resolve would make relation answer "indirect" for every copy the incomplete
// pin does not name — a version-exact statement read out of a file that turned
// out not to make it. Falling back to the name-keyed answer is the honest
// move, and that answer is already withheld when the tree holds two copies.
func TestAnUnresolvableDeclarationDisqualifiesThePin(t *testing.T) {
	g := npmLockGraph([]byte(`{
	  "lockfileVersion": 3,
	  "packages": {
	    "": {},
	    "packages/app": { "version": "1.0.0", "dependencies": { "commander": "^7.2.0" } },
	    "packages/app/node_modules/commander": { "version": "7.2.0" },
	    "packages/toolkit": { "version": "1.0.0", "devDependencies": { "commander": "^11.0.0" } }
	  }
	}`))
	r := ref("npm", "commander")
	if !g.direct[r] {
		t.Fatal("commander is not direct at all")
	}
	if g.pinned[r] {
		t.Error("commander was pinned although one of its two declarations resolved to nothing")
	}
	// Name-keyed still: a lone copy is direct, and a second copy makes it say
	// nothing rather than guess.
	wantRelation(t, g, "npm", "commander", "7.2.0", relDirect)
	ambiguous := map[string]bool{r: true}
	if got := g.relation(component{ecosystem: "npm", name: "commander", version: "7.2.0"}, ambiguous); got != relUnstated {
		t.Errorf("with two copies: %q, want it to say nothing", describe(got))
	}
}

// One manifest's pin may not answer for another manifest's package.
//
// A scan covering two projects — one with a package-lock.json, which states
// the resolved version of a direct dependency, and one with a yarn v1 lockfile
// or a composer.json, which does not — merged the two graphs and unioned the
// pins. relation then took the pinned branch for the second project's copy and
// answered "indirect", a version-exact statement neither file made, and the
// safeguard for ambiguous names was unreachable because it sits on the
// unpinned path.
func TestAPinFromOneManifestDoesNotSpeakForAnother(t *testing.T) {
	pinned := newGraph()
	pinned.pin(ref("npm", "commander"), "15.0.0")

	nameOnly := newGraph()
	nameOnly.direct[ref("npm", "commander")] = true

	for _, order := range []struct {
		name string
		a, b graph
	}{
		{"pinned first", pinned, nameOnly},
		{"pinned second", nameOnly, pinned},
	} {
		t.Run(order.name, func(t *testing.T) {
			var g graph
			g.merge(order.a)
			g.merge(order.b)
			if g.pinned[ref("npm", "commander")] {
				t.Fatal("a pin survived a merge with a manifest that named the same package without one")
			}
			ambiguous := map[string]bool{ref("npm", "commander"): true}
			c := component{ecosystem: "npm", name: "commander", version: "7.2.0"}
			if got := g.relation(c, ambiguous); got != relUnstated {
				t.Errorf("relation = %q, want it to say nothing", describe(got))
			}
		})
	}

	// Two pinned manifests keep their pins: the merge only steps back where a
	// manifest actually declined to say which version.
	t.Run("both pinned", func(t *testing.T) {
		other := newGraph()
		other.pin(ref("npm", "commander"), "7.2.0")
		var g graph
		g.merge(pinned)
		g.merge(other)
		wantRelation(t, g, "npm", "commander", "15.0.0", relDirect)
		wantRelation(t, g, "npm", "commander", "7.2.0", relDirect)
		wantRelation(t, g, "npm", "commander", "8.3.0", relIndirect)
	})
}

// Where a format does not pin the version, a name-keyed direct set may not be
// repeated about a package the tree holds two of: the project asked for *a*
// commander and this is one of three, and which one is not recorded.
func TestAnAmbiguousNameIsNotClaimedDirect(t *testing.T) {
	g := newGraph()
	g.direct[ref("RubyGems", "rack")] = true
	one := component{ecosystem: "RubyGems", name: "rack", version: "2.2.4"}

	if got := g.relation(one, nil); got != relDirect {
		t.Errorf("with one copy: %q, want direct", describe(got))
	}
	ambiguous := map[string]bool{ref("RubyGems", "rack"): true}
	if got := g.relation(one, ambiguous); got != relUnstated {
		t.Errorf("with two copies: %q, want it to say nothing", describe(got))
	}
}

// And the reader is told, because "pulled in by express" reads as a fact about
// the version in front of them when the file only records the name.
func TestChainsSayWhenTheNameIsAmbiguous(t *testing.T) {
	g := newGraph()
	g.indirect[ref("npm", "lodash")] = true
	g.require(ref("npm", "express"), ref("npm", "lodash"))
	inv := inventory{
		structure: g,
		ambiguous: map[string]bool{ref("npm", "lodash"): true},
		all: []component{
			{ecosystem: "npm", name: "lodash", version: "3.10.1"},
			{ecosystem: "npm", name: "lodash", version: "4.17.21"},
		},
	}
	got := whereFrom(inv, inv.all[0])
	for _, want := range []string{"one of 2 copies here", "pulled in by express"} {
		if !strings.Contains(got, want) {
			t.Errorf("whereFrom = %q, missing %q", got, want)
		}
	}
}
