// A lockfile is untrusted input, and a dependency graph is a shape somebody
// else chose. The walk has to cost what rta decided it costs — not what the
// file's author did.
func TestTheWalkIsBoundedOnAHostileShape(t *testing.T) {
	// Every package requires every package in the level below it, so the
	// number of distinct chains to the bottom grows as the product of the
	// widths. Nothing here is direct, so nothing terminates early.
	const levels, width = 40, 40
	g := newGraph()
	for l := 0; l < levels-1; l++ {
		for i := 0; i < width; i++ {
			for j := 0; j < width; j++ {
				g.require(ref("npm", "l"+itoa(l)+"n"+itoa(i)), ref("npm", "l"+itoa(l+1)+"n"+itoa(j)))
			}
		}
	}
	done := make(chan int, 1)
	go func() { done <- len(g.via(ref("npm", "l39n0"), maxWhyChains, maxWhyDepth)) }()
	select {
	case n := <-done:
		if n > maxWhyChains {
			t.Errorf("the chain bound did not hold: %d chains", n)
		}
	case <-time.After(10 * time.Second):
		t.Fatal("via did not terminate on a wide graph")
	}
}

func itoa(n int) string { return strconv.Itoa(n) }

// The words a finding uses, because they are what decides the next hour:
// "direct" means bump a version in a file you own, "pulled in by express"
// means the fix belongs to express.
func TestWhereFromSaysWhatToDoNext(t *testing.T) {
	g := newGraph()
	g.direct[ref("npm", "express")] = true
	g.indirect[ref("npm", "qs")] = true
	g.indirect[ref("npm", "orphan")] = true
	g.require(ref("npm", "express"), ref("npm", "qs"))

	for _, tc := range []struct {
		name, want string
	}{
		{"express", "a direct dependency"},
		{"qs", "indirect, pulled in by express"},
		// Listed as indirect and nothing requires it: some formats state the
		// split without recording the edges. Half an answer beats none, and
		// beats an invented chain by more.
		{"orphan", "indirect"},
		// Neither stated nor reachable. Silence is the honest answer.
		{"stranger", ""},
	} {
		got := whereFrom(inventory{structure: g}, component{ecosystem: "npm", name: tc.name})
		if got != tc.want {
			t.Errorf("whereFrom(%s) = %q, want %q", tc.name, got, tc.want)
		}
	}
}

