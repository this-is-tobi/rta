// Each fixture is a cut-down copy of what the tool actually writes, keeping
// the shapes that decide the parse — the peer-dependency suffix pnpm appends,
// the workspace entry Berry records and v1 does not, the `files = [` array
// Poetry puts between a package and its dependency table.

func chains(t *testing.T, g graph, eco, name string) []string {
	t.Helper()
	var out []string
	for _, c := range g.via(ref(eco, name), maxWhyChains, maxWhyDepth) {
		names := make([]string, 0, len(c))
		for _, r := range c {
			names = append(names, refName(r))
		}
		out = append(out, strings.Join(names, ">"))
	}
	sort.Strings(out)
	return out
}

func wantChains(t *testing.T, g graph, eco, name string, want ...string) {
	t.Helper()
	sort.Strings(want)
	if got := chains(t, g, eco, name); !reflect.DeepEqual(got, want) {
		t.Errorf("chains to %s: got %v, want %v", name, got, want)
	}
}

// wantRelation asks about a package at a version, because that is what a
// component is: a name with no version is not a row any report ever holds, and
// the formats that pin a direct dependency pin it *at* a version.
func wantRelation(t *testing.T, g graph, eco, name, version, want string) {
	t.Helper()
	c := component{ecosystem: eco, name: name, version: version}
	if got := g.relation(c, nil); got != want {
		t.Errorf("%s %s is %q, want %q", name, version, describe(got), describe(want))
	}
}

func describe(rel string) string {
	if rel == relUnstated {
		return "not stated"
	}
	return rel
}

