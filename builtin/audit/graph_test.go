// A cycle is ordinary in an npm or Cargo graph. A walk that did not say so
// would not terminate, and one that dropped the chain would leave every
// package inside the cycle with no explanation at all.
func TestACycleTerminatesAndStillExplains(t *testing.T) {
	g := newGraph()
	g.require(ref("npm", "a"), ref("npm", "b"))
	g.require(ref("npm", "b"), ref("npm", "c"))
	g.require(ref("npm", "c"), ref("npm", "a"))

	got := chains(t, g, "npm", "c")
	if len(got) == 0 {
		t.Fatal("a package inside a cycle got no explanation")
	}
	for _, c := range got {
		if !strings.Contains(c, deeper) {
			t.Errorf("a chain that never reached a top is not marked as cut: %q", c)
		}
	}
}

// The shortest explanation is the one somebody can act on soonest.
func TestTheShortestChainWins(t *testing.T) {
	g := newGraph()
	g.direct[ref("npm", "top")] = true
	g.require(ref("npm", "top"), ref("npm", "mid"))
	g.require(ref("npm", "mid"), ref("npm", "leaf"))
	g.require(ref("npm", "top"), ref("npm", "leaf"))

	got := g.via(ref("npm", "leaf"), maxWhyChains, maxWhyDepth)
	if len(got) == 0 {
		t.Fatal("no chain found")
	}
	if len(got[0]) != 2 {
		t.Errorf("the first chain should be the shortest, got %v", got[0])
	}
}

// A chain cut by the depth bound and a chain that reached the top render
// identically otherwise, and one of them is a claim about where a dependency
// came from.
func TestADeepChainSaysItWasCut(t *testing.T) {
	g := newGraph()
	prev := ref("npm", "p0")
	for i := 1; i <= maxWhyDepth+3; i++ {
		next := ref("npm", "p"+string(rune('0'+i)))
		g.require(prev, next)
		prev = next
	}
	got := g.via(prev, 1, maxWhyDepth)
	if len(got) != 1 {
		t.Fatalf("want one chain, got %d", len(got))
	}
	if got[0][0] != deeper {
		t.Errorf("a chain cut at the depth bound is not marked: %v", got[0])
	}
	if len(got[0]) != maxWhyDepth+1 {
		t.Errorf("the depth bound did not hold: %v", got[0])
	}
}

// PEP 503: names compare case-insensitively with -, _ and . equivalent. The
// formats really do spell one package two ways in one file.
func TestPyPINamesAreNormalised(t *testing.T) {
	for _, tc := range []struct{ in, want string }{
		{"Jinja2", "jinja2"},
		{"typing_extensions", "typing-extensions"},
		{"zope.interface", "zope-interface"},
		{"ruamel.yaml.clib", "ruamel-yaml-clib"},
		{"Flask", "flask"},
	} {
		if got := normalizePyPI(tc.in); got != tc.want {
			t.Errorf("normalizePyPI(%q) = %q, want %q", tc.in, got, tc.want)
		}
	}
	// npm is case-sensitive and Go module paths certainly are: normalising
	// them would merge packages that are not the same package.
	if got := ref("npm", "Base64"); got != "npm/Base64" {
		t.Errorf("npm name was normalised: %q", got)
	}
}

// The union rule, and which side wins it: in a monorepo a package can be one
