// The command is chosen from the manifest, not the ecosystem: a JavaScript
// project's ecosystem is "npm" whichever of four package managers put the
// tree there, and `npm why` in a pnpm repository is a wasted paste.
func TestWhyCommandFollowsTheLockfile(t *testing.T) {
	for _, tc := range []struct {
		source, ecosystem, want string
	}{
		{"/x/go.mod", "Go", "go mod why -m lodash"},
		{"/x/pnpm-lock.yaml", "npm", "pnpm why lodash"},
		{"/x/yarn.lock", "npm", "yarn why lodash"},
		{"/x/bun.lock", "npm", "bun pm why lodash"},
		{"/x/package-lock.json", "npm", "npm why lodash"},
		{"/x/Cargo.lock", "crates.io", "cargo tree --invert --package lodash"},
		{"/x/uv.lock", "PyPI", "uv tree --invert --package lodash"},
		{"/x/composer.lock", "Packagist", "composer depends lodash"},
		// An SBOM names no package manager, so the ecosystem is the coarser
		// answer and it is still better than none.
		{"/x/bom.json", "npm", "npm why lodash"},
		{"/x/bom.json", "Maven", "mvn dependency:tree -Dincludes=lodash"},
		{"/x/bom.json", "", ""},
	} {
		got := whyCommand(component{name: "lodash", ecosystem: tc.ecosystem, source: tc.source})
		if got != tc.want {
			t.Errorf("whyCommand(%s, %s) = %q, want %q", tc.source, tc.ecosystem, got, tc.want)
		}
	}
}

