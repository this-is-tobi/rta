// still fail to describe the same package: they key on the name, and one of
// them normalising while the other does not is invisible in either test.
func TestProvenanceReachesTheFinding(t *testing.T) {
	dir := t.TempDir()
	write := func(name, body string) {
		t.Helper()
		if err := os.WriteFile(filepath.Join(dir, name), []byte(body), 0o600); err != nil {
			t.Fatal(err)
		}
	}
	write("package-lock.json", `{
	  "lockfileVersion": 3,
	  "packages": {
	    "": { "dependencies": { "express": "^4.17.1" } },
	    "node_modules/express": { "version": "4.17.1", "dependencies": { "qs": "6.7.0" } },
	    "node_modules/qs": { "version": "6.7.0" }
	  }
	}`)
	write("go.mod", "module example.com/x\n\ngo 1.24\n\nrequire (\n\tgithub.com/a/b v1.0.0\n\tgithub.com/c/d v2.0.0 // indirect\n)\n")

	fsys := os.DirFS(dir)
	names := manifestsIn(fsys, ".")
	inv := read(fsys, names, names)
	if len(inv.all) != 4 {
		t.Fatalf("read %d components, want 4: %+v", len(inv.all), inv.all)
	}
	r := &report{}
	gradeDeps(r, inv, map[string][]string{
		"npm/qs@6.7.0":             {"GHSA-qs"},
		"Go/github.com/c/d@v2.0.0": {"GHSA-cd"},
	}, nil, false, false)

	qs := mustFind(t, r, "qs")
	if !strings.Contains(qs.detail, "indirect, pulled in by express") {
		t.Errorf("qs finding does not say where it came from: %q", qs.detail)
	}
	// go.mod states the split and records no edges, so this is the half-answer
	// case reaching a real report.
	cd := mustFind(t, r, "github.com/c/d")
	if !strings.Contains(cd.detail, "indirect") || strings.Contains(cd.detail, "pulled in by") {
		t.Errorf("a go.mod indirect should be stated without an invented chain: %q", cd.detail)
	}
	// And the report says so, with the command that does have the chain.
	prov := mustFind(t, r, "provenance")
	if !strings.Contains(prov.detail, "go mod why -m github.com/c/d") {
		t.Errorf("provenance finding does not hand over the command: %q", prov.detail)
	}
	count := mustFind(t, r, "dependencies")
	if !strings.Contains(count.detail, "2 asked for by name, 2 pulled in") {
		t.Errorf("inventory line does not split the count: %q", count.detail)
	}
}

// A source string is not a bag of substrings.
//
// isLocalSource matched "path" anywhere in the text it was handed, and it was
// handed the source — so a crate from a git remote whose URL happens to
// contain the word read as "a directory on this machine" and was dropped from
// the inventory entirely: never sent to OSV, never counted, never mentioned. A
// shorter report that looks complete is the worst failure this file has.
func TestAURLContainingAMarkerWordIsNotALocalSource(t *testing.T) {
	const cargo = `[[package]]
name = "app"
version = "0.1.0"
dependencies = ["helper"]

[[package]]
name = "helper"
version = "1.0.0"
source = "git+https://github.com/acme/pathfinder?branch=main#deadbeef"
checksum = "aaa"
dependencies = ["serde"]

[[package]]
name = "serde"
version = "1.0.197"
source = "registry+https://github.com/rust-lang/crates.io-index"
checksum = "bbb"
`
	// The component parser: the crate has to reach the inventory at all.
	var got []string
	for _, c := range parseTOMLLock(cargo, "Cargo.lock", "crates.io", true) {
		got = append(got, c.name)
	}
	sort.Strings(got)
	if !reflect.DeepEqual(got, []string{"helper", "serde"}) {
		t.Errorf("inventory = %v, want both crates — one was read as a local directory", got)
	}

	// And the graph: helper is a dependency of app, not the project.
	g := tomlGraph(cargo, "crates.io", cargoLock)
	wantRelation(t, g, "crates.io", "helper", "1.0.0", relDirect)    // app requires it
	wantRelation(t, g, "crates.io", "serde", "1.0.197", relIndirect) // helper does
	wantChains(t, g, "crates.io", "serde", "helper>serde")
}

