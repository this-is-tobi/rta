// resolvFixture points the plugin at a scratch resolv.conf.
func resolvFixture(t *testing.T, content string) string {
	t.Helper()
	dir := t.TempDir()
	path := filepath.Join(dir, "resolv.conf")
	if err := os.WriteFile(path, []byte(content), 0o644); err != nil {
		t.Fatal(err)
	}
	t.Setenv("RTA_DATA_DIR", t.TempDir())
	orig := resolvConf
	resolvConf = path
	t.Cleanup(func() { resolvConf = orig })
	return path
}

func pairs(t *testing.T, v view.View) map[string]string {
	t.Helper()
	kv, ok := v.(view.KeyValue)
	if !ok {
		t.Fatalf("want KeyValue, got %s", view.TypeOf(v))
	}
	out := map[string]string{}
	for _, p := range kv.Pairs {
		out[p.Key] = p.Value
	}
	return out
}

func TestResolverListReportsServersAndOwnership(t *testing.T) {
	resolvFixture(t, "# a note\nsearch corp.example.com lan\nnameserver 192.168.1.1\nnameserver 9.9.9.9\noptions ndots:2\n")
	got := pairs(t, run(t, runResolverList, nil))

	if got["nameserver"] != "192.168.1.1" {
		t.Errorf("primary = %q", got["nameserver"])
	}
	// The order is the failover order, and shown as such.
	if got["fallback 1"] != "9.9.9.9" {
		t.Errorf("fallback = %q", got["fallback 1"])
	}
	if got["search"] != "corp.example.com lan" {
		t.Errorf("search = %q", got["search"])
	}
	if got["options"] != "ndots:2" {
		t.Errorf("options = %q", got["options"])
	}
	if !strings.Contains(got["managed by"], "safe to edit") {
		t.Errorf("ownership = %q", got["managed by"])
	}
}

