// Writing a generated file is worse than refusing: the change works, then
// vanishes at the next reboot with nothing pointing at why.
func TestResolverSetRefusesAManagedFile(t *testing.T) {
	path := resolvFixture(t, "# Generated by systemd-resolved. DO NOT EDIT.\nnameserver 127.0.0.53\n")
	_, err := runResolverSet(context.Background(),
		plugin.NewRequest(map[string]any{"server": []string{"1.1.1.1"}}, false, true))
	ve := view.AsError(err, "x")
	if ve.Code != "net.sysfile.managed" || ve.Hint == "" {
		t.Fatalf("want net.sysfile.managed with hint, got %+v", ve)
	}
	if data, _ := os.ReadFile(path); strings.Contains(string(data), "1.1.1.1") {
		t.Error("the refusal still wrote the file")
	}
}

// A symlink is how systemd-resolved and friends actually present the file,
// and replacing it with a regular file would break the whole arrangement.
func TestResolverSetRefusesASymlink(t *testing.T) {
	dir := t.TempDir()
	real := filepath.Join(dir, "stub-resolv.conf")
	if err := os.WriteFile(real, []byte("nameserver 127.0.0.53\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	link := filepath.Join(dir, "resolv.conf")
	if err := os.Symlink(real, link); err != nil {
		t.Skipf("symlinks unavailable: %v", err)
	}
	t.Setenv("RTA_DATA_DIR", t.TempDir())
	orig := resolvConf
	resolvConf = link
	t.Cleanup(func() { resolvConf = orig })

	_, err := runResolverSet(context.Background(),
		plugin.NewRequest(map[string]any{"server": []string{"1.1.1.1"}}, false, true))
	ve := view.AsError(err, "x")
	if ve.Code != "net.sysfile.managed" || !strings.Contains(ve.Message, "symlink") {
		t.Fatalf("want a symlink refusal, got %+v", ve)
	}
}

// --force writes anyway, and says the change is going to be undone.
func TestResolverSetForceWarnsItWillBeOverwritten(t *testing.T) {
	path := resolvFixture(t, "# Generated by NetworkManager\nnameserver 192.168.1.1\n")
	body := run(t, runResolverSet, map[string]any{
		"server": []string{"1.1.1.1"}, "force": true,
	}).(view.Text).Body

	if !strings.Contains(body, "warning") || !strings.Contains(body, "NetworkManager") {
		t.Errorf("forced write should repeat the warning: %q", body)
	}
	if data, _ := os.ReadFile(path); !strings.Contains(string(data), "1.1.1.1") {
		t.Errorf("--force did not write:\n%s", data)
	}
}

