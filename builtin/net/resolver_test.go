func TestResolverSetDryRunChangesNothing(t *testing.T) {
	path := resolvFixture(t, "nameserver 192.168.1.1\n")
	v, err := runResolverSet(context.Background(),
		plugin.NewRequest(map[string]any{"server": []string{"1.1.1.1"}}, true, true))
	if err != nil {
		t.Fatal(err)
	}
	if body := v.(view.Text).Body; !strings.HasPrefix(body, "would ") {
		t.Errorf("dry-run = %q", body)
	}
	if data, _ := os.ReadFile(path); !strings.Contains(string(data), "192.168.1.1") {
		t.Error("a dry run modified the file")
	}
}

