// Setting the nameservers replaces those lines and nothing else: search
// domains and options are separate settings that a resolver change should
// not quietly drop.
func TestResolverSetKeepsSearchAndOptions(t *testing.T) {
	path := resolvFixture(t, "# my notes\nsearch corp.example.com\nnameserver 192.168.1.1\noptions ndots:2\n")
	run(t, runResolverSet, map[string]any{"server": []string{"1.1.1.1", "9.9.9.9"}})

	data, err := os.ReadFile(path)
	if err != nil {
		t.Fatal(err)
	}
	got := string(data)
	for _, keep := range []string{"# my notes", "search corp.example.com", "options ndots:2"} {
		if !strings.Contains(got, keep) {
			t.Errorf("lost %q:\n%s", keep, got)
		}
	}
	if !strings.Contains(got, "nameserver 1.1.1.1\nnameserver 9.9.9.9") {
		t.Errorf("new nameservers missing or out of order:\n%s", got)
	}
	if strings.Contains(got, "192.168.1.1") {
		t.Errorf("old nameserver survived:\n%s", got)
	}
}

