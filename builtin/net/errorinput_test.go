func capabilityOf(t *testing.T, id string) plugin.Capability {
	t.Helper()
	for _, c := range Plugin().Capabilities {
		if c.ID == id {
			return c
		}
	}
	t.Fatalf("net declares no %s", id)
	return plugin.Capability{}
}

// refusedInput runs h and returns the refusal it answered with, failing the
// test when it was not code, or when the input it names is one capability id
// does not declare — which every surface ignores, so a misspelt name would
// pass for no name at all.
func refusedInput(t *testing.T, id string, h plugin.Handler, values map[string]any, dryRun bool, code string) *view.Error {
	t.Helper()
	_, err := h(context.Background(), plugin.NewRequest(values, dryRun, true))
	if err == nil {
		t.Fatalf("%s %v: accepted, want %s", id, values, code)
	}
	ve := view.AsError(err, "x")
	if ve.Code != code {
		t.Fatalf("%s %v: %s (%s), want %s", id, values, ve.Code, ve.Message, code)
	}
	if _, ok := capabilityOf(t, id).ErrorInput(ve); ve.Input != "" && !ok {
		t.Fatalf("%s: %s names %q, which it does not declare", id, code, ve.Input)
	}
	return ve
}

// A refusal of one input's value names that input, so a form opens again on
// the box that holds the fix and an agent knows which argument to send again.
// One that no single box holds the fix for — state the file is in, a waiver
// the person has to choose — names none.
func TestARefusalOfOneInputNamesIt(t *testing.T) {
	hostsFixture(t, "127.0.0.1 localhost\n# 10.0.0.5 parked.local\n# 10.0.0.6 parked.local\n")
	resolvFixture(t, "nameserver 1.1.1.1\n")
	scratch := t.TempDir()
	absent := filepath.Join(scratch, "absent")
	generated := filepath.Join(scratch, "resolv.conf")
	if err := os.WriteFile(generated, []byte("# Generated by NetworkManager\nnameserver 1.1.1.1\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	linked := filepath.Join(scratch, "static-hosts")
	if err := os.WriteFile(linked, []byte("127.0.0.1 localhost\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	link := filepath.Join(scratch, "hosts")
	if err := os.Symlink(linked, link); err != nil {
		t.Fatal(err)
	}

	for _, c := range []struct {
		why    string
		id     string
		h      plugin.Handler
		values map[string]any
		code   string
		input  string
	}{
		{"a name with white space around it", "net.dns", runDNS,
			map[string]any{"name": " example.invalid", "type": "auto"}, "net.dns.badname", "name"},
		{"a record type there is no lookup for", "net.dns", runDNS,
			map[string]any{"name": "example.invalid", "type": "bogus"}, "net.dns.badtype", "type"},
		{"more ports than one scan takes", "net.port", runPort,
			map[string]any{"host": "127.0.0.1", "ports": "1-65535"}, "net.port.toomany", "ports"},
		{"a port list that does not parse", "net.port", runPort,
			map[string]any{"host": "127.0.0.1", "ports": "22,ssh"}, "net.port.badspec", "ports"},
		{"a port list with no port in it", "net.port", runPort,
			map[string]any{"host": "127.0.0.1", "ports": ","}, "net.port.empty", "ports"},
		{"a port out of range", "net.probe", runProbe,
			map[string]any{"host": "127.0.0.1", "port": 0}, "net.probe.badport", "port"},
		{"nothing to send but white space", "net.send", runSend,
			map[string]any{"host": "127.0.0.1", "port": 1, "data": " \t"}, "net.send.nodata", "data"},
		{"an address that is not one", "net.hosts.add", runHostsAdd,
			map[string]any{"ip": "api.local", "hostname": []string{"x.local"}}, "net.hosts.badip", "ip"},
		{"no name to point", "net.hosts.add", runHostsAdd,
			map[string]any{"ip": "10.0.0.1", "hostname": []string{}}, "net.hosts.nohostname", "hostname"},
		{"a name the file would read as two", "net.hosts.add", runHostsAdd,
			map[string]any{"ip": "10.0.0.1", "hostname": []string{"x.local", "evil.local 1.2.3.4"}}, "net.hosts.badhostname", "hostname"},
		{"no name to remove", "net.hosts.rm", runHostsRemove,
			map[string]any{"hostname": []string{}}, "net.hosts.nohostname", "hostname"},
		{"a name the file does not hold", "net.hosts.rm", runHostsRemove,
			map[string]any{"hostname": []string{"nope.local"}}, "net.hosts.notfound", "hostname"},
		{"no name to toggle", "net.hosts.toggle", runHostsToggle,
			map[string]any{"hostname": ""}, "net.hosts.nohostname", "hostname"},
		{"a name with white space around it", "net.hosts.toggle", runHostsToggle,
			map[string]any{"hostname": " localhost"}, "net.hosts.badhostname", "hostname"},
		{"a name the file does not hold", "net.hosts.toggle", runHostsToggle,
			map[string]any{"hostname": "nope.local"}, "net.hosts.notfound", "hostname"},
		{"a name parked at two addresses, which is the file's state", "net.hosts.toggle", runHostsToggle,
			map[string]any{"hostname": "parked.local"}, "net.hosts.ambiguous", ""},
		{"no nameserver", "net.resolver.set", runResolverSet,
			map[string]any{"server": []string{}}, "net.resolver.noserver", "server"},
		{"a nameserver that is a name", "net.resolver.set", runResolverSet,
			map[string]any{"server": []string{"1.1.1.1", "dns.example"}}, "net.resolver.badserver", "server"},

		{"a file that is not there", "net.hosts.list", runHostsList,
			map[string]any{"file": absent}, "net.sysfile.unreadable", "file"},
		{"a directory for a file", "net.hosts.list", runHostsList,
			map[string]any{"file": scratch}, "net.sysfile.notafile", "file"},
		{"a file that is not there", "net.hosts.add", runHostsAdd,
			map[string]any{"ip": "10.0.0.1", "hostname": []string{"x.local"}, "file": absent}, "net.sysfile.unreadable", "file"},
		{"a file that is not there", "net.hosts.rm", runHostsRemove,
			map[string]any{"hostname": []string{"localhost"}, "file": absent}, "net.sysfile.unreadable", "file"},
		{"a file that is not there", "net.hosts.toggle", runHostsToggle,
			map[string]any{"hostname": "localhost", "file": absent}, "net.sysfile.unreadable", "file"},
		{"a file that is a symbolic link", "net.hosts.add", runHostsAdd,
			map[string]any{"ip": "10.0.0.1", "hostname": []string{"x.local"}, "file": link}, "net.sysfile.managed", "file"},
		{"a file that is not there", "net.resolver.list", runResolverList,
			map[string]any{"file": absent}, "net.sysfile.unreadable", "file"},
		{"a file that is not there", "net.resolver.set", runResolverSet,
			map[string]any{"server": []string{"1.1.1.1"}, "file": absent}, "net.sysfile.unreadable", "file"},
		{"a generated file, which force waives", "net.resolver.set", runResolverSet,
			map[string]any{"server": []string{"1.1.1.1"}, "file": generated}, "net.sysfile.managed", ""},
	} {
		t.Run(c.id+": "+c.why, func(t *testing.T) {
			if ve := refusedInput(t, c.id, c.h, c.values, true, c.code); ve.Input != c.input {
				t.Errorf("%s names input %q, want %q: %s", ve.Code, ve.Input, c.input, ve.Message)
			}
		})
	}

	ve := refusedInput(t, "net.send", runSend,
		map[string]any{"host": "127.0.0.1", "port": 70000, "data": "PING\r\n"}, true, "net.probe.badport")
	if ve.Input != "port" {
		t.Errorf("net.send's dry run: %s names input %q, want port", ve.Code, ve.Input)
	}
}

// The system's own hosts file and resolv.conf, which a call that names no file
// works on, are no input of the call's: a form reopened on the empty box would
// point at nothing anybody typed.
func TestTheSystemsOwnFileIsNoInput(t *testing.T) {
	scratch := t.TempDir()
	t.Setenv("RTA_DATA_DIR", t.TempDir())
	origHosts, origResolv := hostsFile, resolvConf
	t.Cleanup(func() { hostsFile, resolvConf = origHosts, origResolv })
	hostsFile, resolvConf = filepath.Join(scratch, "absent-hosts"), filepath.Join(scratch, "absent-resolv.conf")

	for id, h := range map[string]plugin.Handler{"net.hosts.list": runHostsList, "net.resolver.list": runResolverList} {
		if ve := refusedInput(t, id, h, nil, false, "net.sysfile.unreadable"); ve.Input != "" {
			t.Errorf("%s of the system's file names input %q", id, ve.Input)
		}
	}

	linked := filepath.Join(scratch, "static-hosts")
	if err := os.WriteFile(linked, []byte("127.0.0.1 localhost\n"), 0o644); err != nil {
		t.Fatal(err)
	}
	hostsFile = filepath.Join(scratch, "hosts")
	if err := os.Symlink(linked, hostsFile); err != nil {
		t.Fatal(err)
	}
	ve := refusedInput(t, "net.hosts.add", runHostsAdd,
		map[string]any{"ip": "10.0.0.1", "hostname": []string{"x.local"}}, true, "net.sysfile.managed")
	if ve.Input != "" {
		t.Errorf("a linked system hosts file names input %q", ve.Input)
	}
}

// A host the resolver answered does not exist is the host input's fault — a
// mistyped name — and its refusal names it. A resolver that did not answer, or
// a connection the host refused, names none: the host may be right, and the
// network is what failed.
func TestOnlyANameThatDoesNotExistNamesTheHost(t *testing.T) {
	notFound := &stdnet.DNSError{Err: "no such host", Name: "nope.invalid", IsNotFound: true}
	for why, c := range map[string]struct {
		err   error
		input string
	}{
		"a name that does not exist":         {notFound, "host"},
		"one a dial ran into":                {&stdnet.OpError{Op: "dial", Net: "tcp", Err: notFound}, "host"},
		"a resolver that did not answer":     {&stdnet.DNSError{Err: "i/o timeout", Name: "nope.invalid", IsTimeout: true}, ""},
		"a resolver that failed":             {&stdnet.DNSError{Err: "server misbehaving", Name: "nope.invalid", IsTemporary: true}, ""},
		"a name that resolved to no address": {nil, ""},
		"a connection the host refused":      {&stdnet.OpError{Op: "dial", Net: "tcp", Err: syscall.ECONNREFUSED}, ""},
	} {
		if got := namingHost(view.Errorf("net.probe.unreachable", "connecting: %v", c.err), c.err).Input; got != c.input {
			t.Errorf("%s: names input %q, want %q", why, got, c.input)
		}
	}
}

// notFoundInput is the input a refusal of a host that did not resolve names:
// the host when the resolver answered that the name does not exist, and none
// when it could not be asked, which is all a machine with no network can say
// of any lookup.
func notFoundInput(ve *view.Error) string {
	if strings.Contains(ve.Message, "no such host") {
		return "host"
	}
	return ""
}

// A hosts file or a resolv.conf that is there and that this process may not
// read names no input: the path is right, and the fix is a chmod, not the box.
func TestASystemFileThatCannotBeReadNamesNoInput(t *testing.T) {
	if os.Geteuid() == 0 {
		t.Skip("mode bits do not stop this reader")
	}
	shut := filepath.Join(t.TempDir(), "hosts")
	if err := os.WriteFile(shut, []byte("127.0.0.1 localhost\n"), 0o600); err != nil {
		t.Fatal(err)
	}
	if err := os.Chmod(shut, 0o000); err != nil {
		t.Fatal(err)
	}
	for id, h := range map[string]plugin.Handler{"net.hosts.list": runHostsList, "net.resolver.list": runResolverList} {
		if ve := refusedInput(t, id, h, map[string]any{"file": shut}, false, "net.sysfile.unreadable"); ve.Input != "" {
			t.Errorf("%s: names %q, want none", id, ve.Input)
		}
	}
}
